#ifndef HARL_HPP
#define HARL_HPP

#include <iostream>
#include <string>

// Harl class: complains at different log levels using pointers to member functions
class Harl
{
    private:
        void debug(void);
        void info(void);
        void warning(void);
        void error(void);

    public:
        Harl(void);
        ~Harl(void);

        // Member function calling private level functions without if/else forest
        void complain(std::string level);
};

#endif