#ifndef CLAPTRAP_HPP
# define CLAPTRAP_HPP

# include <iostream>

class ClapTrap {
    // Each object owns its own name, HP, energy and damage.
    protected:
        // Derived classes can access these members; outside callers cannot.
        std::string _name;
        unsigned int _hit;
        int         _energy;
        int         _damage;

    public:
        // Canonical form: default/copy construction, assignment, destruction.
        ClapTrap(void);
        ClapTrap(std::string name);
        ClapTrap(const ClapTrap &copy);
        ClapTrap &operator=(const ClapTrap &copy);
        ~ClapTrap(void);

        void attack(const std::string& target);
        void takeDamage(unsigned int amount);
        void beRepaired(unsigned int amount);
};

#endif
